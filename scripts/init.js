#!/usr/bin/env node
/**
 * Generates a ready-to-run deployment directory: docker-compose.yml, config.yaml
 * and .env, with fresh secrets and first-login administrator credentials.
 *
 * Intended to be run from the published image, so that deploying needs nothing
 * but Docker and no copy of this repository:
 *
 *   docker run --rm -v "$PWD:/out" pandosme/dataq-analyzer:latest init
 *
 * It can also be run from a checkout:
 *
 *   npm run init -- ./deployment
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, '..');

const args = process.argv.slice(2);
const force = args.includes('--force');
const useExternalMongo = args.includes('--external-mongodb');
const positional = args.filter((arg) => !arg.startsWith('--'));
const targetDir = path.resolve(positional[0] || process.env.OUT_DIR || '/out');

// Secrets are generated locally and never leave this machine.
const secret = (bytes = 36) => crypto.randomBytes(bytes).toString('base64url');
// Readable but high-entropy, so it survives being typed once at first login.
const passphrase = () => `${secret(6)}-${secret(6)}-${secret(6)}`;

const flagValue = (name) => {
  const prefix = `--${name}=`;
  const match = args.find((arg) => arg.startsWith(prefix));
  return match ? match.slice(prefix.length) : '';
};

// MQTT is how device data arrives, but the app refuses to start with
// mqtt.enabled and no broker URL. Supply one here and it is enabled outright;
// leave it out and MQTT is written disabled so the first start still succeeds.
const mqttBrokerUrl = flagValue('mqtt-broker-url') || process.env.MQTT_BROKER_URL || '';
const mqttEnabled = Boolean(mqttBrokerUrl);

const adminUsername = process.env.ADMIN_USERNAME || 'admin';
const adminPassword = process.env.ADMIN_PASSWORD || passphrase();
const port = process.env.DATAQ_PORT || '3303';

const composeFile = useExternalMongo
  ? 'docker-compose.yml'
  : 'docker-compose.yml:docker-compose.mongodb.yml';

const appService = `services:
  app:
    image: pandosme/dataq-analyzer:\${DATAQ_VERSION:-latest}
    container_name: dataq-analyzer
    ports:
      # Bound to loopback: put a TLS-terminating reverse proxy in front of it
      # before exposing this to a network.
      - "127.0.0.1:\${DATAQ_PORT:-3303}:80"
    environment:
      NODE_ENV: production
      PORT: 80
      CORS_ORIGIN: \${CORS_ORIGIN:-*}
      MONGODB_URI: \${MONGODB_URI}
      MQTT_BROKER_URL: \${MQTT_BROKER_URL:-}
      MQTT_USERNAME: \${MQTT_USERNAME:-}
      MQTT_PASSWORD: \${MQTT_PASSWORD:-}
      MEDIAMTX_USERNAME: \${MEDIAMTX_USERNAME:-}
      MEDIAMTX_PASSWORD: \${MEDIAMTX_PASSWORD:-}
      JWT_SECRET: \${JWT_SECRET:?Set JWT_SECRET in .env}
      JWT_EXPIRES_IN: \${JWT_EXPIRES_IN:-7d}
      CREDENTIAL_ENCRYPTION_KEY: \${CREDENTIAL_ENCRYPTION_KEY:?Set CREDENTIAL_ENCRYPTION_KEY in .env}
      BOOTSTRAP_ADMIN_USERNAME: \${BOOTSTRAP_ADMIN_USERNAME:-}
      BOOTSTRAP_ADMIN_PASSWORD: \${BOOTSTRAP_ADMIN_PASSWORD:-}
      CONFIG_PATH: /app/config.yaml
    volumes:
      - ./config.yaml:/app/config.yaml:ro
    restart: unless-stopped
`;

const mongoService = `
services:
  app:
    depends_on:
      mongodb:
        condition: service_healthy

  mongodb:
    image: mongo:7
    container_name: dataq-analyzer-mongodb
    volumes:
      - mongodb_data:/data/db
    healthcheck:
      test: ["CMD", "mongosh", "--quiet", "--eval", "db.adminCommand('ping').ok"]
      interval: 10s
      timeout: 5s
      retries: 10
    restart: unless-stopped

volumes:
  mongodb_data:
    driver: local
`;

const envFile = `# Generated by "dataq-analyzer init" on ${new Date().toISOString()}
# Treat this file as a secret. Do not commit it.

DATAQ_VERSION=latest
DATAQ_PORT=${port}
COMPOSE_FILE=${composeFile}

# Origin the browser uses. Set this to your real URL once a proxy is in front.
CORS_ORIGIN=*

${
  useExternalMongo
    ? '# Point this at your existing MongoDB.\nMONGODB_URI=mongodb://mongodb.example.com:27017/dataq-analyzer'
    : '# Bundled MongoDB container from docker-compose.mongodb.yml.\nMONGODB_URI=mongodb://mongodb:27017/dataq-analyzer'
}

# Required when mqtt.enabled is true in config.yaml. This is how device data
# arrives, so most installations need it.
MQTT_BROKER_URL=${mqttBrokerUrl}
MQTT_USERNAME=
MQTT_PASSWORD=

# Generated locally. Changing JWT_SECRET logs everyone out. Losing
# CREDENTIAL_ENCRYPTION_KEY makes stored device credentials unrecoverable.
JWT_SECRET=${secret()}
JWT_EXPIRES_IN=7d
CREDENTIAL_ENCRYPTION_KEY=${secret()}

# Used only while no administrator exists in the database. Blank these out
# after the first successful login.
BOOTSTRAP_ADMIN_USERNAME=${adminUsername}
BOOTSTRAP_ADMIN_PASSWORD=${adminPassword}

# Required only when playback is enabled in config.yaml. These credentials are
# sent only from the analyzer to MediaMTX; they are never exposed to browsers.
MEDIAMTX_USERNAME=
MEDIAMTX_PASSWORD=
`;

function writeFileSafely(name, contents, mode = 0o644) {
  const destination = path.join(targetDir, name);
  if (fs.existsSync(destination) && !force) {
    console.log(`  skipped  ${name} (already exists, use --force to replace)`);
    return false;
  }
  fs.writeFileSync(destination, contents, { mode });
  console.log(`  wrote    ${name}`);
  return true;
}

function main() {
  if (!fs.existsSync(targetDir)) {
    console.error(`Target directory does not exist: ${targetDir}`);
    console.error('Mount a directory at /out, or pass one as an argument.');
    process.exit(1);
  }

  try {
    fs.accessSync(targetDir, fs.constants.W_OK);
  } catch {
    console.error(`Target directory is not writable: ${targetDir}`);
    console.error('Try: docker run --rm --user "$(id -u):$(id -g)" -v "$PWD:/out" pandosme/dataq-analyzer:latest init');
    process.exit(1);
  }

  console.log(`\nInitialising a DataQ Analyzer deployment in ${targetDir}\n`);

  writeFileSafely('docker-compose.yml', appService);
  if (!useExternalMongo) writeFileSafely('docker-compose.mongodb.yml', mongoService);

  // Ship the same defaults the image was built with, so the file can be edited
  // rather than written from scratch.
  const defaultConfig = path.join(projectRoot, 'config.yaml');
  if (fs.existsSync(defaultConfig)) {
    const template = fs
      .readFileSync(defaultConfig, 'utf8')
      .replace(/^(mqtt:\n(?:.*\n)*?\s*enabled:\s*)\S+/m, `$1${mqttEnabled}`);
    writeFileSafely('config.yaml', template);
  } else {
    console.log('  skipped  config.yaml (default template not found in this image)');
  }

  const wroteEnv = writeFileSafely('.env', envFile, 0o600);

  console.log('\nNext steps:\n');
  if (mqttEnabled) {
    console.log(`  1. MQTT is enabled and pointed at ${mqttBrokerUrl} — add credentials to .env if the broker needs them.`);
  } else {
    console.log('  1. Set MQTT_BROKER_URL in .env and mqtt.enabled: true in config.yaml to ingest device data.');
  }
  console.log('  2. Review config.yaml — app name, retention, and which features are enabled.');
  console.log('  3. Start it:      docker compose up -d');
  console.log('  4. Watch it boot: docker compose logs -f app');
  console.log(`  5. Open:          http://localhost:${port}\n`);

  if (wroteEnv) {
    console.log('First login (this is the only time it is shown):\n');
    console.log(`  username: ${adminUsername}`);
    console.log(`  password: ${adminPassword}\n`);
    console.log('Blank BOOTSTRAP_ADMIN_USERNAME and BOOTSTRAP_ADMIN_PASSWORD in .env');
    console.log('once you have logged in, then run: docker compose up -d\n');
  }
}

main();
